import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://localhost:3000';
const mobile = process.argv[3] === 'm';
const b = await chromium.launch();
const p = await b.newPage({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 900 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0, 200)); });
await p.addInitScript(() => localStorage.setItem('kroj.consent.v1', JSON.stringify({ decided: true, analytics: true, marketing: false })));
await p.goto(base + '/proizvod/prenj-dzemper-okruglog-izreza', { waitUntil: 'networkidle' });
await p.getByRole('button', { name: /Dodaj u korpu/ }).first().click();
await p.waitForTimeout(300);
console.log('size error shown:', await p.getByText('Odaberite veličinu da biste dodali u korpu.').isVisible());
await p.getByRole('button', { name: /^M(,|$)/ }).first().click();
await p.getByRole('button', { name: /Dodaj u korpu/ }).first().click();
await p.waitForTimeout(700);
await p.screenshot({ path: '/tmp/shots/flow-1-drawer.png' });
await p.getByRole('link', { name: 'Nastavi na naplatu' }).click();
await p.waitForURL('**/naplata');
await p.waitForTimeout(500);
await p.getByRole('button', { name: /Potvrdi narudžbu/ }).click();
await p.waitForTimeout(300);
await p.screenshot({ path: '/tmp/shots/flow-2-errors.png', fullPage: true });
await p.getByLabel('Ime i prezime').fill('Amir Hodžić');
await p.getByLabel('Broj telefona').fill('061 234 567');
await p.getByLabel('Ulica i kućni broj').fill('Ferhadija 12');
await p.getByLabel('Grad ili mjesto').fill('Sarajevo');
await p.getByLabel('Poštanski broj').click();
console.log('zip autofill:', await p.getByLabel('Poštanski broj').inputValue());
await p.getByRole('checkbox', { name: /Prihvatam/ }).check();
await p.getByRole('button', { name: /Potvrdi narudžbu/ }).click();
await p.waitForURL('**/narudzba/**', { timeout: 10000 });
await p.waitForTimeout(600);
await p.screenshot({ path: '/tmp/shots/flow-3-confirm.png', fullPage: true });
console.log('url:', p.url());
const ev = await p.evaluate(() => (window.__krojEvents || []).map((e) => e.event));
console.log('events:', ev.join(', '));
console.log('errors:', errs.slice(0, 5));
await b.close();
